CREATE OR REPLACE FUNCTION update_modified_column()   
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;   
END;
$$ language 'plpgsql';

CREATE TRIGGER update_users_modtime BEFORE UPDATE ON users FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_appointment_modtime BEFORE UPDATE ON appointment FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_treatment_record_modtime BEFORE UPDATE ON treatment_record FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_payment_modtime BEFORE UPDATE ON payment FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_schedule_modtime BEFORE UPDATE ON schedule FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_leave_record_modtime BEFORE UPDATE ON leave_record FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_clinic_settings_modtime BEFORE UPDATE ON clinic_settings FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_treatment_plan_modtime BEFORE UPDATE ON treatment_plan FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_installment_modtime BEFORE UPDATE ON installment FOR EACH ROW EXECUTE PROCEDURE update_modified_column();

