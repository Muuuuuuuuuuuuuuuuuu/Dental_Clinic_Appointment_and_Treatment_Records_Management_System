-- ==========================================
-- 11. CUSTOM TRIGGERS (Appointment Overlap)
-- ==========================================
CREATE OR REPLACE FUNCTION check_appointment_overlap()
RETURNS TRIGGER AS $$
BEGIN
    -- 1. เช็กคิวซ้อนของทันตแพทย์
    IF EXISTS (
        SELECT 1 FROM appointment
        WHERE dentist_id = NEW.dentist_id
          AND appointment_date = NEW.appointment_date
          AND appointment_id != COALESCE(NEW.appointment_id, -1)
          AND appointment_status NOT IN ('ยกเลิก', 'ไม่มาตามนัด')
          AND (NEW.start_time < end_time_est AND NEW.end_time_est > start_time)
    ) THEN
        RAISE EXCEPTION 'คิวทับซ้อน: ทันตแพทย์ท่านนี้มีคิวในช่วงเวลาดังกล่าวแล้ว';
    END IF;

    -- 2. เช็กคิวซ้อนของคนไข้
    IF EXISTS (
        SELECT 1 FROM appointment
        WHERE patient_id = NEW.patient_id
          AND appointment_date = NEW.appointment_date
          AND appointment_id != COALESCE(NEW.appointment_id, -1)
          AND appointment_status NOT IN ('ยกเลิก', 'ไม่มาตามนัด')
          AND (NEW.start_time < end_time_est AND NEW.end_time_est > start_time)
    ) THEN
        RAISE EXCEPTION 'คิวซ้ำซ้อน: คนไข้มีคิวทำฟันในช่วงเวลาดังกล่าวแล้ว';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_check_appointment_overlap
BEFORE INSERT OR UPDATE ON appointment
FOR EACH ROW
EXECUTE FUNCTION check_appointment_overlap();
