-- 1.1 ข้อมูลส่วนตัวพื้นฐาน
CREATE TABLE IF NOT EXISTS public.profile (
  citizen_id VARCHAR(13) NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  gender TEXT CHECK (gender = ANY (ARRAY['ชาย'::text, 'หญิง'::text])),
  birth_date DATE,
  phone_number VARCHAR(15),
  current_address TEXT,
  CONSTRAINT profile_pkey PRIMARY KEY (citizen_id)
);

-- 1.2 ข้อมูลบัญชีผู้ใช้งานระบบ (เชื่อมโยงกับ Supabase Auth)
CREATE TABLE IF NOT EXISTS public.users (
  user_id UUID NOT NULL,
  citizen_id VARCHAR(13),
  email VARCHAR(100),
  role TEXT CHECK (role = ANY (ARRAY['ทันตแพทย์'::text, 'คนไข้'::text, 'พนักงาน'::text, 'admin'::text])),
  account_status TEXT CHECK (account_status = ANY (ARRAY['active'::text, 'inactive'::text, 'suspended'::text])) DEFAULT 'active',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT users_pkey PRIMARY KEY (user_id),
  CONSTRAINT users_citizen_id_fkey FOREIGN KEY (citizen_id) REFERENCES public.profile(citizen_id) ON DELETE SET NULL
);

-- 1.3 ทันตแพทย์
CREATE TABLE IF NOT EXISTS public.dentist (
  dentist_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id UUID,
  title_name VARCHAR(50),
  specialization VARCHAR(255),
  license_number VARCHAR(50) NOT NULL,
  start_date DATE,
  image_url TEXT,
  is_active BOOLEAN DEFAULT true,
  university TEXT,
  graduation_year INTEGER,
  CONSTRAINT dentist_pkey PRIMARY KEY (dentist_id),
  CONSTRAINT dentist_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(user_id) ON DELETE SET NULL
