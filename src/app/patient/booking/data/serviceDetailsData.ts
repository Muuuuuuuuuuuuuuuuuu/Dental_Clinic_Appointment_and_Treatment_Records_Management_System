/**
 * ฟังก์ชันช่วยค้นหาข้อมูลรายละเอียดบริการ โดยค้นหาทั้งชื่อเต็มและคีย์เวิร์ดที่เกี่ยวข้อง
 */
export function getServiceDetail(title: string): ServiceDetail {
  if (!title) return DEFAULT_SERVICE_DETAIL;

  // 1. ค้นหาชื่อตรงกันแบบ 100%
  if (SERVICE_DETAILS[title]) {
    return SERVICE_DETAILS[title];
  }

  // 2. ค้นหาแบบจับคู่คีย์เวิร์ด
  const t = title.toLowerCase();
  if (t.includes("จัดฟันแบบโลหะ") || t.includes("metal braces") || t.includes("ปรึกษาจัดฟัน")) {
    return SERVICE_DETAILS["ปรึกษาจัดฟันแบบโลหะ (Metal Braces)"];
  }
  if (t.includes("เซรามิก") || t.includes("ceramic")) {
    return SERVICE_DETAILS["จัดฟันแบบเซรามิก"];
  }
  if (t.includes("invisalign") || t.includes("จัดฟันใส") || t.includes("จัดฟันแบบใส")) {
    return SERVICE_DETAILS["จัดฟันแบบใส (Invisalign)"];
  }
  if (t.includes("ขูดหินปูน")) {
    return SERVICE_DETAILS["ขูดหินปูนและขัดฟัน"];
  }
  if (t.includes("ตรวจ") || t.includes("สุขภาพช่องปาก")) {
    return SERVICE_DETAILS["ตรวจสุขภาพช่องปาก"];
  }
  if (t.includes("x-ray") || t.includes("เอกซเรย์") || t.includes("รังสี")) {
    return SERVICE_DETAILS["ถ่ายภาพรังสีฟัน (X-Ray)"];
  }
  if (t.includes("อุดฟัน")) {
    return SERVICE_DETAILS["อุดฟันสีเหมือนฟัน"];
  }
  if (t.includes("ฟลูออไรด์")) {
    return SERVICE_DETAILS["เคลือบฟลูออไรด์"];
  }
  if (t.includes("ผ่าฟันคุด") || t.includes("ฟันคุด")) {
    return SERVICE_DETAILS["ผ่าฟันคุด"];
  }
  if (t.includes("ถอนฟัน")) {
    return SERVICE_DETAILS["ถอนฟัน"];
  }
  if (t.includes("รักษารากฟัน") || t.includes("รากฟัน")) {
    return SERVICE_DETAILS["รักษารากฟัน"];
  }
  if (t.includes("ฟอกสีฟัน") || t.includes("ฟอกฟัน")) {
    return SERVICE_DETAILS["ฟอกสีฟัน"];
  }
  if (t.includes("รากฟันเทียม") || t.includes("implant")) {
    return SERVICE_DETAILS["รากฟันเทียม (Implant)"];
  }
  if (t.includes("เด็ก")) {
    return SERVICE_DETAILS["ทันตกรรมเด็ก"];
  }

  return DEFAULT_SERVICE_DETAIL;
}
