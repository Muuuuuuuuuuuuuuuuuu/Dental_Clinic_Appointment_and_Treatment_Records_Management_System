-- 15. AUTOMATIC CRON JOB (Auto-Cleanup No-Shows)
-- ==========================================
-- เปิดใช้งาน Extension pg_cron (Supabase รองรับโดย default)
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- ตั้งเวลาทำงานทุกวันตอนเที่ยงคืน (00:00 น. เวลาไทย คือ 17:00 UTC)
-- กวาดล้างคิวที่ค้างเป็น "ยืนยันการจอง", "รอการยืนยัน", "รอรักษา" ของวันที่ผ่านมา ให้กลายเป็น "ไม่มาตามนัด"
SELECT cron.schedule(
  'auto-cancel-no-shows',
  '0 17 * * *',
  $$
    UPDATE appointment
    SET appointment_status = 'ไม่มาตามนัด'
    WHERE appointment_date <= CURRENT_DATE 
      AND appointment_status IN ('รอการยืนยัน', 'ยืนยันการจอง', 'รอรักษา');
  $$
);
