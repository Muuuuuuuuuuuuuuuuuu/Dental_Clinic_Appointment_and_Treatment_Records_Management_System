-- รันคำสั่งนี้ใน Supabase SQL Editor
-- ============================================================================

-- ลบตารางเก่า (ถ้ามี)
DROP TABLE IF EXISTS password_resets CASCADE;

-- สร้างตาราง password_resets
CREATE TABLE password_resets (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  email VARCHAR(100) NOT NULL,
  otp_code VARCHAR(6) NOT NULL,
  is_verified BOOLEAN DEFAULT FALSE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ให้สิทธิ์ทุก role เข้าถึงตาราง
GRANT ALL ON TABLE password_resets TO postgres, anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- เปิด RLS (Row Level Security)
ALTER TABLE password_resets ENABLE ROW LEVEL SECURITY;

-- สร้าง Policy ให้ anon/authenticated สามารถ INSERT, SELECT, UPDATE, DELETE ได้
CREATE POLICY "Allow all access to password_resets" ON password_resets
  FOR ALL
  USING (true)
  WITH CHECK (true);
