-- ==============================================================================
-- 1. BASE TABLES & PROFILES
-- ==============================================================================

-- 1.1 Users: แฟ้มข้อมูลผู้ใช้งาน (เชื่อมต่อกับ auth.users ของ Supabase)
CREATE TABLE users (
  user_id UUID PRIMARY KEY, -- แนะนำให้เชื่อมกับ REFERENCES auth.users(id)
  email VARCHAR(100) UNIQUE,
  role TEXT CHECK (role IN ('ทันตแพทย์', 'คนไข้', 'พนักงาน', 'admin')),
  account_status TEXT CHECK (account_status IN ('active', 'inactive', 'suspended')) DEFAULT 'active',
  last_login TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 1.2 Profile: แฟ้มข้อมูลส่วนตัวพื้นฐาน
-- ปรับแก้: ใช้ profile_id เป็น PK แบบ UUID เพื่อความเป็นสากล และให้ citizen_id เป็น UNIQUE
CREATE TABLE profile (
  profile_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES users(user_id) ON DELETE CASCADE,
  citizen_id VARCHAR(13) UNIQUE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  gender TEXT CHECK (gender IN ('ชาย', 'หญิง')),
  birth_date DATE,
  phone_number VARCHAR(15),
  current_address TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 1.3 Dentist: แฟ้มข้อมูลทันตแพทย์
CREATE TABLE dentist (
  dentist_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID REFERENCES users(user_id) ON DELETE CASCADE,
  title_name VARCHAR(50),
  specialization VARCHAR(255),
  license_number VARCHAR(50) NOT NULL,
  license_expiry DATE,
  start_date DATE,
  image_url TEXT,
  is_active BOOLEAN DEFAULT true -- สำหรับ Soft Delete
);

-- 1.4 Patient: แฟ้มข้อมูลคนไข้
CREATE TABLE patient (
  patient_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID REFERENCES users(user_id) ON DELETE CASCADE,
  allergy_history VARCHAR(255),
  underlying_disease VARCHAR(255),
  emergency_contact_name VARCHAR(100),
  emergency_contact_phone VARCHAR(10),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 1.5 Staff: แฟ้มข้อมูลพนักงาน
CREATE TABLE staff (
  staff_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID REFERENCES users(user_id) ON DELETE CASCADE,
  position VARCHAR(100),
  salary DECIMAL(10,2),
  employment_status TEXT CHECK (employment_status IN ('ปฏิบัติงานปกติ', 'ลาออก', 'พักงาน')) DEFAULT 'ปฏิบัติงานปกติ',
  hire_date DATE
);

-- ==============================================================================
-- 2. SERVICES & PRICING
-- ==============================================================================

-- 2.1 Service: แฟ้มข้อมูลบริการ
CREATE TABLE service (
  service_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  service_name VARCHAR(255) NOT NULL,
  base_price DECIMAL(10,2),
  estimated_time INT, -- เวลาโดยประมาณ (นาที)
  service_category TEXT,
  icon_name VARCHAR(50),
  color_code VARCHAR(20),
  service_type VARCHAR(50),
  description TEXT,
  is_fixed_price BOOLEAN DEFAULT false,
  is_active BOOLEAN DEFAULT true
);

-- 2.2 Dentist_Service: บริการที่หมอแต่ละท่านทำได้
CREATE TABLE dentist_service (
  dentist_service_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  dentist_id BIGINT REFERENCES dentist(dentist_id) ON DELETE CASCADE,
  service_id BIGINT REFERENCES service(service_id) ON DELETE CASCADE,
  UNIQUE(dentist_id, service_id)
);

-- 2.3 Payment_Plan: แผนการชำระเงิน
CREATE TABLE payment_plan (
  plan_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  service_id BIGINT REFERENCES service(service_id) ON DELETE CASCADE,
  plan_name VARCHAR(100) NOT NULL,
  total_amount DECIMAL(10,2),
  installments INT DEFAULT 1,
  per_month DECIMAL(10,2),
  down_payment DECIMAL(10,2) DEFAULT 0
);

-- ==============================================================================
-- 3. APPOINTMENTS & TREATMENTS
-- ==============================================================================

-- 3.1 Appointment: แฟ้มข้อมูลการนัดหมาย
CREATE TABLE appointment (
  appointment_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  patient_id BIGINT REFERENCES patient(patient_id),
  dentist_id BIGINT REFERENCES dentist(dentist_id), -- เพิ่ม dentist_id เพื่อให้รู้ว่านัดใคร
  appointment_date DATE NOT NULL,
  start_time TIME NOT NULL,
  end_time_est TIME,
  appointment_status TEXT CHECK (appointment_status IN ('ยืนยันการจอง', 'รอรักษา', 'กำลังรักษา', 'เสร็จสิ้น', 'ยกเลิก', 'รอชำระเงิน', 'ชำระเงินแล้ว', 'รอการยืนยัน', 'ไม่มาตามนัด')) DEFAULT 'รอการยืนยัน',
  channel TEXT CHECK (channel IN ('Walk-in', 'ออนไลน์')) DEFAULT 'ออนไลน์',
  plan_id BIGINT REFERENCES payment_plan(plan_id) ON DELETE SET NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3.2 Appointment_Detail: รายละเอียดบริการในนัดหมาย
CREATE TABLE appointment_detail (
  app_detail_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  appointment_id BIGINT REFERENCES appointment(appointment_id) ON DELETE CASCADE,
  service_id BIGINT REFERENCES service(service_id),
  price_at_booking DECIMAL(10,2) -- เก็บราคา ณ วันที่จอง เผื่ออนาคตราคาเปลี่ยน
);

-- 3.3 Treatment_Record: บันทึกการรักษา
CREATE TABLE treatment_record (
  treatment_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  appointment_id BIGINT UNIQUE REFERENCES appointment(appointment_id) ON DELETE CASCADE,
  dentist_id BIGINT REFERENCES dentist(dentist_id),
  patient_id BIGINT REFERENCES patient(patient_id),
  treatment_date DATE DEFAULT CURRENT_DATE,
  doctor_note TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3.4 Treatment_Detail: รายละเอียดการรักษา
CREATE TABLE treatment_detail (
  td_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  treatment_id BIGINT REFERENCES treatment_record(treatment_id) ON DELETE CASCADE,
  service_id BIGINT REFERENCES service(service_id),
  tooth_number VARCHAR(10),
  diagnosis TEXT,
  actual_price DECIMAL(10,2)
);

-- 3.5 Payment: การชำระเงิน
CREATE TABLE payment (
  payment_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  treatment_id BIGINT UNIQUE REFERENCES treatment_record(treatment_id),
  staff_id BIGINT REFERENCES staff(staff_id),
  total_amount DECIMAL(10,2) NOT NULL,
  payment_method TEXT CHECK (payment_method IN ('เงินสด', 'โอนเงิน', 'บัตรเครดิต')),
  payment_status TEXT CHECK (payment_status IN ('ค้างชำระ', 'ชำระแล้ว')) DEFAULT 'ค้างชำระ',
  paid_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ==============================================================================
-- 4. CLINIC MANAGEMENT (Queue, Schedule, Leave, Settings)
-- ==============================================================================

-- 4.1 Schedule: ตารางเวรการทำงาน
CREATE TABLE schedule (
  schedule_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID REFERENCES users(user_id) ON DELETE CASCADE,
  day_of_week INT CHECK (day_of_week BETWEEN 0 AND 6),
  start_shift TIME,
  end_shift TIME,
  is_off BOOLEAN DEFAULT false,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4.2 Queue: การจัดการคิวประจำวัน
CREATE TABLE queue (
  queue_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  appointment_id BIGINT UNIQUE REFERENCES appointment(appointment_id) ON DELETE CASCADE,
  queue_number INT,
  check_in_time TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  queue_status TEXT CHECK (queue_status IN ('รอเรียก', 'กำลังรักษา', 'เสร็จสิ้น', 'ยกเลิก')) DEFAULT 'รอเรียก'
);

-- 4.3 Leave_Record: บันทึกวันหยุด/ลา
CREATE TABLE leave_record (
  leave_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID REFERENCES users(user_id) ON DELETE CASCADE,
  leave_date DATE,
  leave_period TEXT CHECK (leave_period IN ('เต็มวัน', 'ครึ่งวันเช้า', 'ครึ่งวันบ่าย')) DEFAULT 'เต็มวัน',
  leave_type TEXT CHECK (leave_type IN ('ลาพักร้อน', 'ลาป่วย', 'คลินิกปิด')),
  is_approved BOOLEAN DEFAULT false,
  reason TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4.4 Review: รีวิวหลังรับบริการ
CREATE TABLE review (
  review_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  appointment_id BIGINT UNIQUE REFERENCES appointment(appointment_id) ON DELETE CASCADE,
  patient_id BIGINT REFERENCES patient(patient_id) ON DELETE CASCADE,
  rating INT CHECK (rating BETWEEN 1 AND 5),
  comment TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4.5 Clinic_Settings & Holidays
CREATE TABLE clinic_settings (
  setting_key VARCHAR(100) PRIMARY KEY,
  setting_value TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE clinic_holiday (
  holiday_id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  holiday_date DATE UNIQUE NOT NULL,
  holiday_name VARCHAR(100) NOT NULL,
  is_recurring BOOLEAN DEFAULT false
);

-- ==============================================================================
-- 5. TRIGGERS (Auto-update updated_at)
-- ==============================================================================
CREATE OR REPLACE FUNCTION update_modified_column()   
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;   
END;
$$ language 'plpgsql';

CREATE TRIGGER update_users_modtime BEFORE UPDATE ON users FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_profile_modtime BEFORE UPDATE ON profile FOR EACH ROW EXECUTE PROCEDURE update_modified_column();
CREATE TRIGGER update_appointment_modtime BEFORE UPDATE ON appointment FOR EACH ROW EXECUTE PROCEDURE update_modified_column();

-- ==============================================================================
-- 6. ROW LEVEL SECURITY (RLS)
-- คำเตือน: ปิดไว้เป็น true สำหรับช่วง Dev หากนำไปขึ้น Production ควรปรับแก้
-- ==============================================================================

DO $$ DECLARE
  r RECORD;
BEGIN
  FOR r IN (SELECT tablename FROM pg_tables WHERE schemaname = current_schema()) LOOP
    EXECUTE 'ALTER TABLE ' || quote_ident(r.tablename) || ' ENABLE ROW LEVEL SECURITY';
    EXECUTE 'CREATE POLICY "Allow all for dev" ON ' || quote_ident(r.tablename) || ' FOR ALL USING (true) WITH CHECK (true)';
  END LOOP;
END $$;

